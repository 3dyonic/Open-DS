// Scheme specimens follow the site theme: the device setting, or the theme switch.
// Each scheme's tokens (tokens/dist/<id>/tokens.scoped.css) carry a dark block that applies under a
// "dark" class. This copies those blocks, keyed to the [data-scheme] element itself, so every
// specimen on the site draws in its scheme's dark theme when the site is dark: when the device is
// dark and the theme switch has not chosen light, or when the switch has chosen dark. A specimen
// that must stay light (the Light button on the applied screen) sets data-mode="light".
// Writes src/generated/specimens-dark.css, which globals.css imports.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dist = join(here, "..", "..", "tokens", "dist");
const outFile = join(here, "..", "src", "generated", "specimens-dark.css");

// A selector from a dark block, rewritten to match without the class. Selectors where .dark sits
// inside the scheme element (for a nested dark island) are dropped: the media query covers the
// scheme element itself.
function rewrite(selector) {
  const s = selector.trim();
  const scheme = s.indexOf("[data-scheme=");
  const dark = s.indexOf(".dark");
  if (scheme < 0 || dark < 0) return null;
  const end = s.indexOf("]", scheme) + 1;
  if (dark >= end) {
    // .dark is on the scheme element only when it follows the attribute directly.
    if (s.slice(end, end + 5) !== ".dark") return null;
  }
  // A standalone ".dark" (an ancestor) goes with its space; a compound one (X.dark) goes alone.
  const plain = s
    .replace(/(^|\s)\.dark(?=\s)/g, "$1")
    .replace(/\.dark/g, "")
    .replace(/\s+/g, " ")
    .trim();
  const attr = plain.match(/\[data-scheme="[^"]+"\]/)[0];
  return plain.replace(attr, `${attr}:not([data-mode="light"])`);
}

const blocks = [];
for (const id of readdirSync(dist).sort()) {
  let css;
  try {
    css = readFileSync(join(dist, id, "tokens.scoped.css"), "utf8");
  } catch {
    continue;
  }
  for (const m of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const selectors = m[1].replace(/\/\*[\s\S]*?\*\//g, "").split(",");
    if (!selectors.some((x) => x.includes(".dark"))) continue;
    const rewritten = [...new Set(selectors.map(rewrite).filter(Boolean))];
    if (rewritten.length) blocks.push({ selectors: rewritten, body: m[2] });
  }
}

if (!blocks.length)
  throw new Error(`No dark token blocks found in ${dist}. Build the tokens first.`);
const under = (prefix) =>
  blocks
    .map((b) => `${b.selectors.map((x) => `${prefix} ${x}`).join(",\n")} {${b.body}}`)
    .join("\n\n");
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  [
    "/* Generated by site/scripts/dark-specimens.mjs. Do not edit. */",
    "@media (prefers-color-scheme: dark) {",
    under(':root:not([data-theme="light"])'),
    "}",
    "",
    under(':root[data-theme="dark"]'),
    "",
  ].join("\n"),
);
console.log(`dark specimens: ${blocks.length} blocks → ${outFile}`);
