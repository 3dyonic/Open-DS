import type { SidebarsConfig } from "@docusaurus/plugin-content-docs";
import { readFileSync } from "node:fs";

// One sidebar per scheme, each its own folder (scripts/generate.mjs). The pages' order is in front matter.
const schemes = JSON.parse(readFileSync(new URL("./schemes.json", import.meta.url), "utf8")) as { id: string }[];
const sidebars: SidebarsConfig = Object.fromEntries(
  schemes.map((s) => [s.id, [{ type: "autogenerated", dirName: s.id }]]),
);

export default sidebars;
