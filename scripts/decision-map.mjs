// The decision map (OD-295): for one scheme, every semantic property with its value, its reason, how
// that reason reaches the scheme's answers, and what is still open. Generated from the trace engine,
// so it always matches the schemes. Written as HTML, which Google Docs imports with its headings and
// tables.
//
//   node scripts/decision-map.mjs <out-dir> [scheme …]
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { execFileSync } from "node:child_process";
import { shown } from "../cli/src/anatomy.mjs";
import { aliasChain, owns, tokenIndex } from "../cli/src/lands.mjs";
import { grammar, loadScheme, questions, schemeIds } from "../cli/src/schemes.mjs";
import { LINKS, reasonOf, traceScheme, weakReasons } from "../cli/src/trace.mjs";

const JIRA = "https://juice-engine.atlassian.net/browse/";
const esc = (s) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const SCOPE_ORDER = ["typography", "color", "spacing", "shape", "elevation", "motion", "iconography", "accessibility", "theming"];
// Tokens no scope's owns list names, by their first segment.
const FALLBACK = { "component-spacing-map": "spacing", icon: "iconography", size: "spacing", "border-width": "shape" };

/** The scope that owns a semantic token: the most specific owns entry, then the fallback by prefix. */
function scopeOf(token, g) {
  let best = null;
  for (const scope of g.scopes)
    for (const o of scope.owns ?? []) if (owns(token, o) && (!best || o.length > best.o.length)) best = { id: scope.id, o };
  return best?.id ?? FALLBACK[token.split(".")[0]] ?? "other";
}

// Where a reason comes from, in plain words, so a reviewer knows what is decided and what to check.
function provenance(t, r, scheme) {
  if (r.kind === "own" && r.by === "pick") {
    const generated = t.links.find((l) => l.by === "pick")?.why && /:\d[\d.]*:1|above the [\d.]+:1 floor/.test(r.why);
    return generated ? "Theme pick, with its measured contrast" : "Theme pick";
  }
  if (r.by === "own") return "Written for this token (OD-293), to review";
  if (r.by === "group") return "Generated by its group's rule";
  if (r.kind === "exact-rule") return "A usage rule that names this token";
  return "No reason of its own";
}

function value(ix, token) {
  const path = ix.byPath.has(token) ? token : `${token}.@`;
  const v = shown(aliasChain(ix, path).value);
  const rem = /^([\d.]+)rem$/.exec(v);
  return rem ? `${v} (${+(parseFloat(rem[1]) * 16).toFixed(1)}px)` : v;
}

export function decisionMap(id, g = grammar()) {
  const scheme = loadScheme(id);
  const asked = questions(g);
  const answers = new Map(scheme.answers.map((a) => [a.question, a]));
  const say = (q) => {
    const a = answers.get(q);
    const option = asked[q]?.options?.find((o) => o.id === a?.option);
    return `<b>${esc(q)}</b> · ${esc(asked[q]?.text)} <i>${esc(option?.label ?? "?")}</i>${a?.why ? ` · ${esc(a.why)}` : ""}`;
  };
  const brand = Object.keys(scheme.tokens.brands)[0];
  const light = tokenIndex(scheme, { brand, mode: "light" });
  const dark = tokenIndex(scheme, { brand, mode: "dark" });
  const trace = traceScheme(scheme, g);
  const weak = new Map(weakReasons(trace).map((w) => [w.token, w.problem]));
  const title = Object.fromEntries(LINKS.map((l) => [l.id, l.title]));
  const commit = execFileSync("git", ["rev-parse", "--short", "HEAD"]).toString().trim();
  const branch = execFileSync("git", ["rev-parse", "--abbrev-ref", "HEAD"]).toString().trim();

  const byScope = Map.groupBy(trace.tokens, (t) => scopeOf(t.token, g));
  const scopes = [...byScope.keys()].sort((a, b) => (SCOPE_ORDER.indexOf(a) + 99) % 99 - (SCOPE_ORDER.indexOf(b) + 99) % 99);
  const counts = Object.fromEntries(
    ["own", "exact-rule", "borrowed", "none"].map((k) => [k, trace.tokens.filter((t) => reasonOf(t).kind === k).length]),
  );
  const drafted = trace.tokens.filter((t) => reasonOf(t).by === "own").length;

  const html = [];
  html.push(`<h1>${esc(scheme.name)} · Decision map</h1>`);
  html.push(
    `<p>Every semantic property of ${esc(scheme.name)}, the design decision behind it, and its reason. Review it scope by scope; each answer goes into the grammar, and the reasons then cite it. Ticket: <a href="${JIRA}OD-295">OD-295</a>. Related: <a href="${JIRA}OD-293">OD-293</a> (trace engine), <a href="${JIRA}OD-294">OD-294</a> (grammar gaps).</p>`,
  );
  html.push(
    `<p><i>Generated by scripts/decision-map.mjs from branch ${esc(branch)} at ${esc(commit)}. Regenerate it after a change; do not edit the values here.</i></p>`,
  );
  html.push(`<h2>Summary</h2><ul>`);
  html.push(`<li>${trace.total} semantic properties. ${trace.total - weak.size} have a reason that explains their value.</li>`);
  html.push(`<li>${counts.own} have a reason of their own; ${counts["exact-rule"]} take a usage rule that names exactly them.</li>`);
  html.push(`<li>${drafted} reasons were written for their token on 2026-11-12 (OD-293). They rest on this scheme's answers, and they wait for your review.</li>`);
  html.push(`<li>Scope rounds in the Ask UI: typography is decided (font weight follows the hierarchy, the typeface and legibility; line height by role kind, tight or open; sizes generated from a ratio). Spacing is next.</li>`);
  html.push(`</ul>`);
  html.push(`<h2>How to read a property</h2><ul>`);
  html.push(`<li><b>Value</b>: in light mode, then dark mode when it differs (brand ${esc(brand)}).</li>`);
  html.push(`<li><b>Reason</b>: why this value, in this scheme. <b>Source</b>: where the reason lives and who decided it.</li>`);
  html.push(`<li><b>Decisions</b>: the answers the reason follows, with each answer's own why. <b>Also linked</b>: other rules that reach the value.</li>`);
  html.push(`</ul>`);

  for (const scope of scopes) {
    const s = g.scopes.find((x) => x.id === scope);
    const list = byScope.get(scope);
    html.push(`<h2>${esc(s?.title ?? scope)}</h2>`);
    if (s) {
      html.push(`<p>${esc(s.description)}</p><p><b>The scope's answers</b></p><ul>`);
      for (const q of s.questions) html.push(`<li>${say(q.id)}</li>`);
      html.push(`</ul>`);
    }
    for (const t of list) {
      const r = reasonOf(t);
      const v = value(light, t.token);
      const vd = value(dark, t.token);
      const others = t.links.filter((l) => !(l.why && l.why === r.why));
      html.push(`<h3>${esc(t.token)}</h3><table>`);
      html.push(`<tr><td><b>Value</b></td><td>${esc(v)}${vd !== v ? ` · dark: ${esc(vd)}` : ""}</td></tr>`);
      html.push(`<tr><td><b>Reason</b></td><td>${esc(r.why ?? "No reason of its own.")}</td></tr>`);
      html.push(`<tr><td><b>Source</b></td><td>${esc(provenance(t, r, scheme))}${weak.has(t.token) ? ` · <b>Open:</b> ${esc(weak.get(t.token))}` : ""}</td></tr>`);
      html.push(`<tr><td><b>Decisions</b></td><td>${(r.because ?? []).map(say).join("<br>") || "None"}</td></tr>`);
      if (others.length)
        html.push(
          `<tr><td><b>Also linked</b></td><td>${others
            .map((l) => `${esc(title[l.by])}${l.situation ? ` (${esc(l.situation)})` : ""}: ${esc(l.why ?? l.says ?? "")} → ${esc(l.because.join(", "))}`)
            .join("<br>")}</td></tr>`,
        );
      html.push(`</table>`);
    }
  }

  html.push(`<h2>Open grammar gaps (OD-294)</h2><ul>`);
  for (const gap of [
    "Line width: the shape scope owns border-width, but its questions are all about corners.",
    "Line height per role kind and type sizes from a ratio: decided in the typography round; the build work is in progress.",
    "Dark-mode shadows: nothing records why dark mode uses a heavier black.",
    "Category hues: nothing records why there are this many.",
    ...(id === "multi-brand" ? ["Corners per brand: the answers say only that each brand sets its own corner."] : []),
    ...(id === "content-first" ? ["size.row: spacing.roles answers that there is no row role, yet the scheme has size.row."] : []),
  ])
    html.push(`<li>${esc(gap)}</li>`);
  html.push(`</ul>`);
  return `<html><head><meta charset="utf-8"><title>${esc(scheme.name)} · Decision map</title></head><body>${html.join("\n")}</body></html>\n`;
}

if (process.argv[1]?.endsWith("decision-map.mjs")) {
  const [out, ...ids] = process.argv.slice(2);
  if (!out) {
    console.error("Usage: node scripts/decision-map.mjs <out-dir> [scheme …]");
    process.exit(1);
  }
  mkdirSync(out, { recursive: true });
  const g = grammar();
  for (const id of ids.length ? ids : schemeIds()) {
    const file = join(out, `${id}.html`);
    writeFileSync(file, decisionMap(id, g));
    console.log(`Wrote ${file}.`);
  }
}
