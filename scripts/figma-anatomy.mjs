// The Open DS anatomy plugin (OD-229), built the way the kits plugin is: generated, not committed.
// It carries every scheme's anatomy data (each drawable component's parts, cards, drawing and kit
// bindings) and the renderer. Run it in a scheme's anatomy file, a file that has that scheme's kit
// library enabled: it draws one page per component, bound to the kit's variables, and lists what the
// kit is missing. It reads the kit and never edits it. When a decision changes, rebuild and run again.
//
//   node scripts/figma-anatomy.mjs [scheme|all]   → figma/anatomy-plugin/ (manifest.json, code.js, ui.html)
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { anatomySpec, drawable, renderer } from "./anatomy-figma/build.mjs";

const ROOT = new URL("..", import.meta.url).pathname;

/** Every scheme's anatomy data: { scheme: { name, library, components: { id: SPEC } } }. */
export function anatomyData(ids) {
  const out = {};
  for (const id of ids) {
    const s = JSON.parse(readFileSync(join(ROOT, `schemes/${id}.json`), "utf8"));
    const components = Object.fromEntries(drawable().map((c) => [c, anatomySpec(c, id)]));
    out[id] = { name: s.name, library: Object.values(components)[0]?.library, components };
  }
  return out;
}

export function writePlugin(dir, ids) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, "manifest.json"),
    `${JSON.stringify(
      {
        name: "Open DS anatomy",
        id: "open-ds-anatomy",
        api: "1.0.0",
        main: "code.js",
        ui: "ui.html",
        editorType: ["figma"],
        documentAccess: "dynamic-page",
        permissions: ["teamlibrary"],
        networkAccess: { allowedDomains: ["none"] },
      },
      null,
      2,
    )}\n`,
  );
  const data = anatomyData(ids);
  const code = renderer();
  writeFileSync(
    join(dir, "code.js"),
    `// Open DS anatomy: draws the Anatomy reference pages of a scheme in the open file, bound to the scheme's
// published kit. Generated by scripts/figma-anatomy.mjs. Do not edit: regenerate.
${code}
const DATA = ${JSON.stringify(data)};
const file = figma.root.name.toLowerCase().replace(/[^a-z]+/g, " ");
const guess = Object.keys(DATA).find((id) => file.includes(id.replace(/-/g, " ")) || file.includes(DATA[id].name.toLowerCase())) || "";
figma.showUI(__html__, { width: 380, height: 420 });
figma.ui.postMessage({
  type: "init",
  guess,
  schemes: Object.fromEntries(Object.entries(DATA).map(([id, s]) => [id, { name: s.name, components: Object.keys(s.components) }])),
});
figma.ui.onmessage = async (msg) => {
  if (msg.type !== "run") return;
  const scheme = DATA[msg.scheme];
  const missing = {};
  let current = "start";
  try {
    figma.ui.postMessage({ type: "progress", text: "Reading " + scheme.library });
    const kit = await loadKit(scheme.library);
    if (!kit.size) throw new Error("This file has no variables from " + scheme.library + ". Enable the library in Assets, then run again.");
    for (const [i, id] of msg.components.entries()) {
      current = id;
      figma.ui.postMessage({ type: "progress", text: (i + 1) + " of " + msg.components.length + ": " + id });
      const r = await renderAnatomy(scheme.components[id], kit);
      for (const [role, why] of Object.entries(r.fallback)) missing[id + " · " + role] = why;
    }
    figma.ui.postMessage({ type: "done", components: msg.components.length, missing });
  } catch (e) {
    figma.ui.postMessage({ type: "progress", text: "Failed at " + current + ": " + (e && e.message ? e.message : String(e)) });
    console.error("Open DS anatomy failed at " + current, e);
  }
};
`,
  );
  writeFileSync(
    join(dir, "ui.html"),
    `<style>body{font:13px Inter,system-ui,sans-serif;margin:16px;color:#16140f}select,button{width:100%;height:32px;margin-top:8px;font:inherit}button{background:#16140f;color:#f6f2e9;border:0;border-radius:4px;font-weight:600}p{color:#645e50}#list{max-height:120px;overflow:auto;margin-top:8px}label{display:block}pre{white-space:pre-wrap;font-size:11px;color:#645e50;max-height:120px;overflow:auto}</style>
<b>Open DS anatomy</b>
<p>Draws the Anatomy reference pages of the scheme in this file, bound to its kit's variables. Running it again redraws them.</p>
<select id="scheme"></select><div id="list"></div><button id="run">Draw the anatomy pages</button><p id="status"></p><pre id="missing"></pre>
<script>
let S = {};
const list = () => { const d = document.getElementById("list"); d.innerHTML = ""; for (const c of S[document.getElementById("scheme").value].components) d.insertAdjacentHTML("beforeend", '<label><input type="checkbox" checked value="' + c + '"> ' + c + "</label>"); };
onmessage = (e) => { const m = e.data.pluginMessage;
  if (m.type === "init") { S = m.schemes; const s = document.getElementById("scheme"); for (const [id, v] of Object.entries(m.schemes)) s.add(new Option(v.name, id, false, id === m.guess)); s.onchange = list; list(); }
  if (m.type === "progress") document.getElementById("status").textContent = m.text;
  if (m.type === "done") { const k = Object.entries(m.missing); document.getElementById("status").textContent = "Drew " + m.components + " components. " + (k.length ? k.length + " values are not in the kit yet; they use the scheme's value:" : "Every value is bound to the kit."); document.getElementById("missing").textContent = k.map(([a, b]) => a + ": " + b).join("\\n"); }
};
document.getElementById("run").onclick = () => parent.postMessage({ pluginMessage: { type: "run", scheme: document.getElementById("scheme").value, components: [...document.querySelectorAll("#list input:checked")].map((x) => x.value) } }, "*");
</script>
`,
  );
  return data;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  // The schemes: every scheme file beside the grammar.
  const all = readdirSync(join(ROOT, "schemes"))
    .filter((f) => f.endsWith(".json") && f !== "grammar.json")
    .map((f) => f.replace(/\.json$/, ""))
    .filter((id) => JSON.parse(readFileSync(join(ROOT, `schemes/${id}.json`), "utf8")).tokens);
  const ids = process.argv[2] && process.argv[2] !== "all" ? [process.argv[2]] : all;
  const data = writePlugin(join(ROOT, "figma/anatomy-plugin"), ids);
  for (const [id, s] of Object.entries(data)) console.log(`${id}: ${Object.keys(s.components).length} components → ${s.library}`);
  console.log("Figma plugin → figma/anatomy-plugin (Plugins, Development, Import plugin from manifest).");
}
